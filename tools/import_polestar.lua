-- AzerothRoute: imports Polestar's guide packs into Guides/Polestar/*.lua.
--
--   luajit tools/import_polestar.lua <Polestar install dir> [<AzerothRoute dir>]
--
-- Reads Polestar_Guides, Polestar_Guides_Horde and Polestar_Guides_Alliance (GPL-3.0-only,
-- Copyright (c) 2026 The Polestar authors), drops the fields AzerothRoute leaves out
-- (spawn spots, walking crumbs, smart-target candidates) and writes one data file per pack.
-- Each guide is wrapped in its own function: Lua 5.1 caps the constants of one function, and the
-- adapter only builds the guides of the player's faction. Polestar's Legs.lua and its quest/item
-- databases are never read. See THIRD_PARTY.md.

local src = arg[1] or error("usage: luajit tools/import_polestar.lua <Polestar dir> [<AzerothRoute dir>]")
local dst = arg[2] or "."

local PACKS = {
    { folder = "Polestar_Guides", pack = "shared", out = "Shared.lua" },
    { folder = "Polestar_Guides_Horde", pack = "horde", out = "Horde.lua" },
    { folder = "Polestar_Guides_Alliance", pack = "alliance", out = "Alliance.lua" },
}

local DROP = { spotsPacked = true, crumbs = true, candidates = true }

local function readGuides(path)
    local guides = {}
    local env = setmetatable({}, { __index = _G })
    env.Polestar = setmetatable({ RegisterGuide = function(g) guides[#guides + 1] = g end },
        { __index = function() return function() end end })
    local chunk = assert(loadfile(path))
    setfenv(chunk, env)
    chunk("Polestar_Guides", {})
    return guides
end

local function isArray(t)
    local n = #t
    for k in pairs(t) do
        if type(k) ~= "number" or k < 1 or k > n or k % 1 ~= 0 then return false end
    end
    return true
end

local function key(k)
    if type(k) == "string" and k:match("^[%a_][%w_]*$") then return k end
    if type(k) == "number" then return "[" .. tostring(k) .. "]" end
    return "[" .. string.format("%q", k) .. "]"
end

local function num(v)
    if v % 1 == 0 then return string.format("%d", v) end
    return string.format("%.10g", v)
end

local function ser(v, ind)
    local t = type(v)
    if t == "string" then return (string.format("%q", v):gsub("\\\n", "\\n")) end
    if t == "number" then return num(v) end
    if t == "boolean" then return tostring(v) end
    if t ~= "table" then error("cannot serialize " .. t) end
    local inner = ind .. "\t"
    local parts = {}
    if isArray(v) then
        local simple = true
        for _, x in ipairs(v) do if type(x) == "table" then simple = false end end
        for _, x in ipairs(v) do parts[#parts + 1] = ser(x, inner) end
        if simple then return "{ " .. table.concat(parts, ", ") .. " }" end
        return "{\n" .. inner .. table.concat(parts, ",\n" .. inner) .. ",\n" .. ind .. "}"
    end
    local keys = {}
    for k, x in pairs(v) do if not DROP[k] then keys[#keys + 1] = k end end
    table.sort(keys, function(a, b)
        if type(a) == type(b) then return a < b end
        return type(a) == "number"
    end)
    for _, k in ipairs(keys) do parts[#parts + 1] = key(k) .. " = " .. ser(v[k], inner) end
    if #parts == 0 then return "{}" end
    return "{\n" .. inner .. table.concat(parts, ",\n" .. inner) .. ",\n" .. ind .. "}"
end

local HEADER = [[
-- Generated by tools/import_polestar.lua from Polestar %s (%s). Do not edit: rerun the tool.
-- Guides Copyright (c) 2026 The Polestar authors, GPL-3.0-only (https://github.com/fitzforge/polestar).
-- Facts inside them come from the sources in Guides/Polestar/LICENSE-DATA.txt. See THIRD_PARTY.md.

local P = _G.AzerothRoute and _G.AzerothRoute.PolestarGuides
if not P then return end
]]

local function version()
    local f = io.open(src .. "/Polestar/Polestar.toc", "rb")
    local v = f and f:read("*a"):match("## Version:%s*([%w%.%-]+)") or "?"
    if f then f:close() end
    return v
end

local ver = version()
local total, totalSteps = 0, 0
for _, p in ipairs(PACKS) do
    local guides = readGuides(src .. "/" .. p.folder .. "/Guides.lua")
    table.sort(guides, function(a, b) return a.id < b.id end)
    local out = { string.format(HEADER, ver, p.folder) }
    for _, g in ipairs(guides) do
        out[#out + 1] = string.format("\nP:Add(%q, %q, function()\n\treturn %s\nend)\n", p.pack, g.id, ser(g, "\t"))
        totalSteps = totalSteps + #(g.steps or {})
    end
    local path = dst .. "/Guides/Polestar/" .. p.out
    local f = assert(io.open(path, "wb"))
    f:write(table.concat(out))
    f:close()
    total = total + #guides
    print(string.format("%-26s %3d guides -> %s", p.folder, #guides, path))
end

-- Polestar's third-party notice for the guide data, kept unchanged.
local nf = assert(io.open(src .. "/Polestar_Guides/LICENSE-DATA.txt", "rb"))
local notice = nf:read("*a")
nf:close()
local of = assert(io.open(dst .. "/Guides/Polestar/LICENSE-DATA.txt", "wb"))
of:write(notice)
of:close()
print(string.format("%d guides, %d steps", total, totalSteps))
